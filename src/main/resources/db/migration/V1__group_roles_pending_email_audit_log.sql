-- Primera migración Flyway del proyecto (antes de esto, el esquema lo creaba
-- Hibernate con ddl-auto=update — ver 06-database/migrations.md).
--
-- Todo el archivo usa IF NOT EXISTS para funcionar correctamente en los DOS
-- escenarios posibles:
--
--  1. Base de datos NUEVA (docker compose down -v && up, o un entorno recién
--     clonado): ninguna tabla existe todavía → los CREATE TABLE de abajo
--     crean el esquema completo tal como lo generan las entidades hoy
--     (incluyendo group_members.role, users.pending_email y admin_audit_log).
--
--  2. Base de datos EXISTENTE (el dev local de cualquiera que venga usando
--     ddl-auto=update hasta ahora): baseline-on-migrate=true (ver
--     application.properties) hace que Flyway marque el esquema actual como
--     "ya migrado" en vez de intentar recrearlo — pero V1 igual SE EJECUTA
--     contra esa base (solo se saltea el baseline, no las migraciones reales
--     posteriores a baseline-version). Ahí los CREATE TABLE IF NOT EXISTS son
--     no-op (ya existen) y lo único que corre de verdad son los ALTER TABLE
--     ADD COLUMN IF NOT EXISTS de group_members/users y el CREATE TABLE de
--     admin_audit_log (que sí es nuevo en ambos escenarios).
--
-- DDL verificado contra un volcado real (pg_dump --schema-only) de una base
-- creada desde cero por Hibernate con las entidades actuales — no es DDL
-- escrito a mano sin contrastar.

-- ─── admin_audit_log ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.admin_audit_log (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action           character varying(20) NOT NULL
                     CONSTRAINT admin_audit_log_action_check
                     CHECK (action IN ('BAN','ACTIVATE','DELETE','ROLE_CHANGE')),
    actor_id         bigint NOT NULL,
    actor_username   character varying(50) NOT NULL,
    created_at       timestamp(6) without time zone,
    details          character varying(500),
    target_id        bigint NOT NULL,
    target_username  character varying(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_log_actor   ON public.admin_audit_log USING btree (actor_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created ON public.admin_audit_log USING btree (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_target  ON public.admin_audit_log USING btree (target_id);

