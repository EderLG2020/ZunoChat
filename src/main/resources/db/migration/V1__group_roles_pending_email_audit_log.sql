-- ─── conversations ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.conversations (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by              bigint,
    ephemeral_enabled       boolean DEFAULT false NOT NULL,
    group_avatar            character varying(500),
    group_name              character varying(100),
    last_message_at         timestamp(6) without time zone,
    last_message_preview    character varying(50),
    last_message_sender_id  bigint,
    muted_user1             boolean NOT NULL,
    muted_user2             boolean NOT NULL,
    status                  character varying(20) NOT NULL
                            CONSTRAINT conversations_status_check
                            CHECK (status IN ('ONLINE','TYPING','OFFLINE','AWAY')),
    type                    character varying(20) DEFAULT 'DIRECT' NOT NULL
                            CONSTRAINT conversations_type_check
                            CHECK (type IN ('DIRECT','GROUP')),
    unread_count_user1      integer NOT NULL,
    unread_count_user2      integer NOT NULL,
    updated_at              timestamp(6) without time zone,
    user1_avatar            character varying(500),
    user1_id                bigint,
    user1_username          character varying(50),
    user2_avatar            character varying(500),
    user2_id                bigint,
    user2_username          character varying(50),
    CONSTRAINT uk_conv_participants UNIQUE (user1_id, user2_id)
);

CREATE INDEX IF NOT EXISTS idx_conv_user1 ON public.conversations USING btree (user1_id, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_conv_user2 ON public.conversations USING btree (user2_id, last_message_at DESC);

-- ─── group_members (ya incluye "role" para una base nueva) ──────────────
CREATE TABLE IF NOT EXISTS public.group_members (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avatar           character varying(500),
    conversation_id  bigint NOT NULL,
    joined_at        timestamp(6) without time zone,
    muted            boolean NOT NULL,
    role             character varying(20) NOT NULL DEFAULT 'MEMBER'
                     CONSTRAINT group_members_role_check
                     CHECK (role IN ('OWNER','ADMIN','MEMBER')),
    unread_count     integer NOT NULL,
    user_id          bigint NOT NULL,
    username         character varying(50) NOT NULL,
    CONSTRAINT uk_group_members_conv_user UNIQUE (conversation_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_group_members_conversation ON public.group_members USING btree (conversation_id);
CREATE INDEX IF NOT EXISTS idx_group_members_user         ON public.group_members USING btree (user_id);

-- Base EXISTENTE: agrega "role" si la tabla ya existía sin esta columna.
-- El creador de cada grupo (conversations.created_by) pasa a OWNER; el resto queda MEMBER.
ALTER TABLE public.group_members ADD COLUMN IF NOT EXISTS role character varying(20);

UPDATE public.group_members gm
SET role = CASE WHEN gm.user_id = c.created_by THEN 'OWNER' ELSE 'MEMBER' END
FROM public.conversations c
WHERE c.id = gm.conversation_id
  AND gm.role IS NULL;

UPDATE public.group_members SET role = 'MEMBER' WHERE role IS NULL; -- filas huérfanas, no debería pasar

ALTER TABLE public.group_members ALTER COLUMN role SET DEFAULT 'MEMBER';
ALTER TABLE public.group_members ALTER COLUMN role SET NOT NULL;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'group_members_role_check') THEN
        ALTER TABLE public.group_members
            ADD CONSTRAINT group_members_role_check CHECK (role IN ('OWNER','ADMIN','MEMBER'));
    END IF;
END $$;

